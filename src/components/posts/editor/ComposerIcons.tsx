// Custom Premium iOS-style animated toggle switch
interface IosSwitchProps {
  checked: boolean;
  onChange: (checked: boolean) => void;
  id?: string;
}

export function IosSwitch({ checked, onChange, id }: IosSwitchProps) {
  return (
    <button
      id={id}
      type="button"
      onClick={() => onChange(!checked)}
      className={cn(
        "relative inline-flex h-7 w-12 shrink-0 cursor-pointer rounded-full border-2 border-transparent transition-colors duration-200 ease-in-out outline-none focus:ring-0",
        checked ? "bg-white" : "bg-[#27272A]"
      )}
    >
      <span
        className={cn(
          "pointer-events-none inline-block h-6 w-6 transform rounded-full shadow-lg ring-0 transition duration-200 ease-in-out",
          checked ? "translate-x-5 bg-black" : "translate-x-0 bg-[#A1A1AA]"
        )}
      />
    </button>
  );
}
